#!/usr/bin/env python3
"""Generate an idiomatic Go SDK for the Blender MCP server.

Parses all MCP tool definitions from ~/Projects/Blender/blender_mcp/mcp/blmcp/tools/*.py
and emits a complete Go package (blender) with:
  - A Client struct that manages the MCP stdio subprocess
  - Builder-pattern method functions for all tools
  - Full doc comments on every function
  - A README.md with usage examples

Usage:
    ./scripts/generate-go-blender-sdk.py [--output DIR] [--verbose]

Output goes to sdk/go/blender/ by default.
"""

