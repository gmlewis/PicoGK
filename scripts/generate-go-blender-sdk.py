def main():
    parser = argparse.ArgumentParser(
        description="Generate the Go (blender) MCP SDK from Blender MCP tool definitions."
    )
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().parent.parent / "sdk" / "go",
        help="Output directory (default: sdk/go/)",
    )
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    tools = parse_all_tools()
    print(f"Parsed {len(tools)} tools from Blender MCP tools")

    if args.verbose:
        for t in tools:
            req = [p.name for p in t.required_params]
            opt = [p.name for p in t.optional_params]
            print(f"  {t.name} ({t.category})")
            print(f"    desc: {t.description[:80]}...")
            if req:
                print(f"    required: {req}")
            if opt:
                print(f"    optional: {opt}")
            print()

    # Create output directories
    pkg_dir = args.output / "blender"
    pkg_dir.mkdir(parents=True, exist_ok=True)

    # Generate files
    client_go = gen_client_go(tools)
    tools_go = gen_tools_go(tools)
    go_mod = gen_go_mod()
    readme_md = gen_readme_md(tools)

    (pkg_dir / "client.go").write_text(client_go)
    (pkg_dir / "tools.go").write_text(tools_go)
    (pkg_dir / "go.mod").write_text(go_mod)
    (pkg_dir / "README.md").write_text(readme_md)

    # Run go fmt on generated source files
    try:
        subprocess.run(["go", "fmt", str(pkg_dir / "client.go"), str(pkg_dir / "tools.go")],
                       check=True, capture_output=True, timeout=30)
    except Exception as e:
        print(f"  Warning: go fmt failed: {e}")

    # Re-read formatted files for accurate line count
    client_lines = len((pkg_dir / "client.go").read_text().splitlines())
    tools_lines = len((pkg_dir / "tools.go").read_text().splitlines())
    readme_lines = len((pkg_dir / "README.md").read_text().splitlines())

    print(f"Generated Go SDK in {pkg_dir}:")
    print(f"  client.go   ({client_lines:>5} lines)")
    print(f"  tools.go    ({tools_lines:>5} lines)")
    print(f"  go.mod")
    print(f"  README.md   ({readme_lines:>5} lines)")
    print(f"\n  Total: {len(tools)} tools across {len(set(t.category for t in tools))} categories")


if __name__ == "__main__":
    main()
