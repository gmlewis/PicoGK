def go_method_name(tool_name: str) -> str:
    """Convert a snake_case tool name to PascalCase Go method name."""
    parts = tool_name.split("_")
    # Go initialism rules
    initialisms = {
        "api": "API", "json": "JSON", "id": "ID", "ids": "IDs",
        "url": "URL", "3d": "3D", "vdb": "VDB",
    }
    result = []
    for p in parts:
        lower = p.lower()
        if lower in initialisms:
            result.append(initialisms[lower])
        elif lower == "for":
            result.append("For")
        elif lower == "cli":
            result.append("CLI")
        elif lower == "blend":
            result.append("Blend")
        elif lower == "file":
            result.append("File")
        else:
            result.append(p.capitalize())
    name = "".join(result)
    # Clean up: "GetBlendfileSummary" -> "GetBlendFileSummary"
    name = re.sub(r"Blendfile", "BlendFile", name)
    name = re.sub(r"Tabby", "TabBy", name)
    return name


def go_struct_name(tool_name: str) -> str:
    """Convert a snake_case tool name to PascalCase Go struct name."""
    return go_method_name(tool_name) + "Request"


def go_field_name(param_name: str) -> str:
    """Convert snake_case param name to Go-idiomatic exported field name."""
    parts = param_name.split("_")
    initialisms = {
        "id": "ID", "ids": "IDs", "api": "API", "json": "JSON",
        "url": "URL", "3d": "3D",
    }
    result = []
    for p in parts:
        lower = p.lower()
        if lower in initialisms:
            result.append(initialisms[lower])
        elif lower == "ui":
            result.append("UI")
        elif lower == "type":
            result.append("Type")
        else:
            result.append(p.capitalize())
    return "".join(result)


