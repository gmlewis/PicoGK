def _go_struct_tag(name: str) -> str:
    """Generate a Go struct tag with backtick delimiters."""
    return '`' + name + '`'


def gen_client_go(tools: list[ToolDef]) -> str:
    """Generate the core client.go file."""
    BQ = '`'  # backtick character
    NL = "'\\n'"  # produces '\n' in Go output

    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    lines.append("package blender\n")
    lines.append("import (")
    lines.append('\t"bufio"')
    lines.append('\t"context"')
    lines.append('\t"encoding/json"')
    lines.append('\t"fmt"')
    lines.append('\t"io"')
    lines.append('\t"log"')
    lines.append('\t"os"')
    lines.append('\t"os/exec"')
    lines.append('\t"path/filepath"')
    lines.append('\t"strings"')
    lines.append('\t"sync"')
    lines.append(")\n")

    # Client type and doc comment
    lines.append("// Client manages a connection to the Blender MCP server.")
    lines.append("// It launches the server as a subprocess and communicates via JSON-RPC over stdio.")
    lines.append("//")
    lines.append("// Usage:")
    lines.append("//")
    lines.append("//\t// Uses default server (blender-mcp)")
    lines.append("//\tclient, err := blender.NewClient(ctx, \"\")")
    lines.append("//\tdefer client.Close()")
    lines.append("//\t// Or specify a custom path:")
    lines.append("//\tclient, err := blender.NewClient(ctx, \"/path/to/blender-mcp\")")
    lines.append("//\t// Execute Python code in Blender")
    lines.append("//\tres, err := client.ExecuteBlenderCode(blender.ExecuteBlenderCodeRequest{")
    lines.append("//\t\tCode: \"import bpy; result = {'objects': [o.name for o in bpy.data.objects]}\",")
    lines.append("//\t})")
    lines.append("type Client struct {")
    lines.append("\tctx       context.Context")
    lines.append("\tcmd       *exec.Cmd")
    lines.append("\tstdin     io.WriteCloser")
    lines.append("\tstdout    *bufio.Reader")
    lines.append("\tmu        sync.Mutex")
    lines.append("\tmsgID     int")
    lines.append("\tserverBin string")
    lines.append("}\n")

    lines.append("// DefaultServerBin is the default command to launch the Blender MCP server.")
    lines.append("// It can be overridden by passing a non-empty path to NewClient.")
    lines.append('const DefaultServerBin = "uv"\n')
    lines.append("// DefaultServerArgs are the default arguments for the Blender MCP server.")
    lines.append('var DefaultServerArgs = []string{"--directory", expandPath("~/Projects/Blender/blender_mcp/mcp/blmcp"), "run", "blender-mcp"}\n')

    # NewClient
    lines.append("// NewClient launches the Blender MCP server and returns a Client.")
    lines.append("// If serverBin is empty, uses the default (uv run blender-mcp).")
    lines.append("// If serverBin is a directory, uses uv --directory <dir> run blender-mcp.")
    lines.append("func NewClient(ctx context.Context, serverBin string) (*Client, error) {")
    lines.append('\tif serverBin == "" {')
    lines.append("\t\treturn newClientWithArgs(ctx, DefaultServerBin, DefaultServerArgs, \"\")")
    lines.append("\t}")
    lines.append("\tserverBin = expandPath(serverBin)")
    lines.append("\t// If it's a directory, use uv --directory <dir> run blender-mcp")
    lines.append('\tif info, err := os.Stat(serverBin); err == nil && info.IsDir() {')
    lines.append('\t\treturn newClientWithArgs(ctx, "uv", []string{"--directory", serverBin, "run", "blender-mcp"}, "")')
    lines.append("\t}")
    lines.append("\t// Otherwise treat as a direct binary/command")
    lines.append("\treturn newClientWithArgs(ctx, serverBin, nil, \"\")")
    lines.append("}\n")

    # newClientWithArgs
    lines.append("func newClientWithArgs(ctx context.Context, bin string, args []string, workDir string) (*Client, error) {")
    lines.append("\tcmd := exec.CommandContext(ctx, bin, args...)")
    lines.append("\tif workDir != \"\" {")
    lines.append("\t\tcmd.Dir = workDir")
    lines.append("\t}")
    lines.append("\tstdin, err := cmd.StdinPipe()")
    lines.append('\tif err != nil {')
    lines.append('\t\treturn nil, fmt.Errorf("creating stdin pipe: %w", err)')
    lines.append("\t}")
    lines.append("\tstdout, err := cmd.StdoutPipe()")
    lines.append('\tif err != nil {')
    lines.append('\t\treturn nil, fmt.Errorf("creating stdout pipe: %w", err)')
    lines.append("\t}")
    lines.append('\tif err := cmd.Start(); err != nil {')
    lines.append('\t\treturn nil, fmt.Errorf("starting server: %w", err)')
    lines.append("\t}")
    lines.append("\tc := &Client{")
    lines.append("\t\tctx:       ctx,")
    lines.append("\t\tcmd:       cmd,")
    lines.append("\t\tstdin:     stdin,")
    lines.append("\t\tstdout:    bufio.NewReader(stdout),")
    lines.append("\t\tserverBin: bin,")
    lines.append("\t}")
    lines.append("\t// Perform MCP initialize handshake")
    lines.append('\tif err := c.initialize(); err != nil {')
    lines.append("\t\tcmd.Process.Kill()")
    lines.append('\t\treturn nil, fmt.Errorf("initialize handshake: %w", err)')
    lines.append("\t}")
    lines.append("\treturn c, nil")
    lines.append("}\n")

    # Close
    lines.append("// Close shuts down the MCP server process.")
    lines.append("func (c *Client) Close() error {")
    lines.append("\tc.mu.Lock()")
    lines.append("\tdefer c.mu.Unlock()")
    lines.append("\tif c.stdin != nil {")
    lines.append("\t\tc.stdin.Close()")
    lines.append("\t}")
    lines.append("\tif c.cmd != nil && c.cmd.Process != nil {")
    lines.append("\t\tdone := make(chan struct{})")
    lines.append("\t\tgo func() {")
    lines.append("\t\t\tc.cmd.Wait()")
    lines.append("\t\t\tclose(done)")
    lines.append("\t\t}()")
    lines.append("\t\tselect {")
    lines.append("\t\tcase <-done:")
    lines.append("\t\tcase <-c.ctx.Done():")
    lines.append("\t\t\tc.cmd.Process.Kill()")
    lines.append("\t\t\t<-done")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn nil")
    lines.append("}\n")

    # expandPath
    lines.append("// expandPath expands a leading ~ to the user's home directory.")
    lines.append("func expandPath(path string) string {")
    lines.append('\tif strings.HasPrefix(path, "~") {')
    lines.append("\t\thome, err := os.UserHomeDir()")
    lines.append("\t\tif err == nil {")
    lines.append("\t\t\tpath = filepath.Join(home, path[1:])")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\treturn path")
    lines.append("}\n")

    # JSON-RPC internals
    lines.append("// --- JSON-RPC internals ---\n")

    lines.append("type jsonRPCRequest struct {")
    lines.append(f"\tJSONRPC string {BQ}json:\"jsonrpc\"{BQ}")
    lines.append(f"\tID      int    {BQ}json:\"id\"{BQ}")
    lines.append(f"\tMethod  string {BQ}json:\"method\"{BQ}")
    lines.append(f"\tParams  any    {BQ}json:\"params\"{BQ}")
    lines.append("}\n")

    lines.append("type jsonRPCResponse struct {")
    lines.append(f"\tJSONRPC string          {BQ}json:\"jsonrpc\"{BQ}")
    lines.append(f"\tID      int             {BQ}json:\"id\"{BQ}")
    lines.append(f"\tResult  json.RawMessage {BQ}json:\"result,omitempty\"{BQ}")
    lines.append(f"\tError   *jsonRPCErr     {BQ}json:\"error,omitempty\"{BQ}")
    lines.append("}\n")

    lines.append("type jsonRPCErr struct {")
    lines.append(f"\tCode    int    {BQ}json:\"code\"{BQ}")
    lines.append(f"\tMessage string {BQ}json:\"message\"{BQ}")
    lines.append("}\n")

    lines.append("type toolResult struct {")
    lines.append("\tContent []struct {")
    lines.append("\t\tType string " + BQ + 'json:"type"' + BQ)
    lines.append("\t\tText string " + BQ + 'json:"text"' + BQ)
    lines.append("\t} " + BQ + 'json:"content"' + BQ)
    lines.append("\tIsError bool " + BQ + 'json:"isError"' + BQ)
    lines.append("}\n")

    # initialize
    lines.append("func (c *Client) initialize() error {")
    lines.append("\treq := map[string]any{")
    lines.append('\t\t"jsonrpc": "2.0",')
    lines.append("\t\t\"id\":      c.nextID(),")
    lines.append('\t\t"method":  "initialize",')
    lines.append('\t\t"params": map[string]any{')
    lines.append('\t\t\t"protocolVersion": "2024-11-05",')
    lines.append('\t\t\t"capabilities":    map[string]any{},')
    lines.append('\t\t\t"clientInfo": map[string]any{')
    lines.append('\t\t\t\t"name":    "blender-go-sdk",')
    lines.append('\t\t\t\t"version": "1.0.0",')
    lines.append("\t\t\t},")
    lines.append("\t\t},")
    lines.append("\t}")
    lines.append("\t_, err := c.call(req)")
    lines.append("\tif err != nil {")
    lines.append("\t\treturn err")
    lines.append("\t}")
    lines.append("\t// Send initialized notification")
    lines.append("\tnotif := map[string]any{")
    lines.append('\t\t"jsonrpc": "2.0",')
    lines.append('\t\t"method":  "notifications/initialized",')
    lines.append("\t}")
    lines.append("\treturn c.send(notif)")
    lines.append("}\n")

    # nextID
    lines.append("func (c *Client) nextID() int {")
    lines.append("\tc.mu.Lock()")
    lines.append("\tdefer c.mu.Unlock()")
    lines.append("\tc.msgID++")
    lines.append("\treturn c.msgID")
    lines.append("}\n")

    # send
    lines.append("func (c *Client) send(msg any) error {")
    lines.append("\tdata, err := json.Marshal(msg)")
    lines.append('\tif err != nil {')
    lines.append('\t\treturn fmt.Errorf("marshaling: %w", err)')
    lines.append("\t}")
    lines.append("\tc.mu.Lock()")
    lines.append("\tdefer c.mu.Unlock()")
    lines.append(f"\t_, err = c.stdin.Write(append(data, {NL}))")
    lines.append("\treturn err")
    lines.append("}\n")

    # callNoParse
    lines.append("func (c *Client) callNoParse(req any) (string, error) {")
    lines.append("\tif err := c.send(req); err != nil {")
    lines.append('\t\treturn "", err')
    lines.append("\t}")
    lines.append("\t// Read response line")
    lines.append(f"\tline, err := c.stdout.ReadString({NL})")
    lines.append('\tif err != nil {')
    lines.append('\t\treturn "", fmt.Errorf("reading response: %w", err)')
    lines.append("\t}")
    lines.append("\treturn line, nil")
    lines.append("}\n")

    # call
    lines.append("func (c *Client) call(req any) (json.RawMessage, error) {")
    lines.append("\tline, err := c.callNoParse(req)")
    lines.append("\tif err != nil {")
    lines.append("\t\treturn nil, err")
    lines.append("\t}")
    lines.append("\tvar resp jsonRPCResponse")
    lines.append("\tif err := json.Unmarshal([]byte(line), &resp); err != nil {")
    lines.append('\t\treturn nil, fmt.Errorf("parsing response: %w (line: %q)", err, line)')
    lines.append("\t}")
    lines.append("\tif resp.Error != nil {")
    lines.append('\t\treturn nil, fmt.Errorf("server error [%d]: %s", resp.Error.Code, resp.Error.Message)')
    lines.append("\t}")
    lines.append("\treturn resp.Result, nil")
    lines.append("}\n")

    # newReq
    lines.append("func (c *Client) newReq(toolName string, args map[string]any) map[string]any {")
    lines.append("\treturn map[string]any{")
    lines.append('\t\t"jsonrpc": "2.0",')
    lines.append("\t\t\"id\":      c.nextID(),")
    lines.append('\t\t"method":  "tools/call",')
    lines.append('\t\t"params": map[string]any{')
    lines.append('\t\t\t"name":      toolName,')
    lines.append('\t\t\t"arguments": args,')
    lines.append("\t\t},")
    lines.append("\t}")
    lines.append("}\n")

    # callToolNoParse
    lines.append("// callToolNoParse invokes an MCP tool by name and returns the raw response.")
    lines.append("func (c *Client) callToolNoParse(toolName string, args map[string]any) (string, error) {")
    lines.append("\treq := c.newReq(toolName, args)")
    lines.append("\tresult, err := c.callNoParse(req)")
    lines.append("\tif err != nil {")
    lines.append('\t\treturn "", err')
    lines.append("\t}")
    lines.append("\treturn string(result), nil")
    lines.append("}\n")

    # callTool
    lines.append("// callTool invokes an MCP tool by name and returns the parsed text content.")
    lines.append("func (c *Client) callTool(toolName string, args map[string]any) (string, error) {")
    lines.append("\treq := c.newReq(toolName, args)")
    lines.append("\tresult, err := c.call(req)")
    lines.append("\tif err != nil {")
    lines.append('\t\treturn "", err')
    lines.append("\t}")
    lines.append("\tvar tr toolResult")
    lines.append("\tif err := json.Unmarshal([]byte(result), &tr); err != nil {")
    lines.append('\t\treturn "", fmt.Errorf("parsing tool result: %w", err)')
    lines.append("\t}")
    lines.append("\tvar text string")
    lines.append("\tfor _, item := range tr.Content {")
    lines.append('\t\tif item.Type == "text" {')
    lines.append("\t\t\ttext += item.Text")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("\tif tr.IsError {")
    lines.append('\t\treturn text, fmt.Errorf("tool error: %s", text)')
    lines.append("\t}")
    lines.append("\treturn text, nil")
    lines.append("}\n")

    # Must
    lines.append("// Must calls Do and must have no error or it will abort the program.")
    lines.append("func (c *Client) Must(cmd any) (label, result string) {")
    lines.append("\tvar err error")
    lines.append("\tlabel, result, err = c.Do(cmd)")
    lines.append("\tif err != nil {")
    lines.append('\t\tlog.Fatalf("FAIL: %v -> %v", label, err)')
    lines.append("\t}")
    lines.append("\treturn label, result")
    lines.append("}\n")

    # Do
    lines.append("// Do executes an MCP tool call, returning a string result and an error.")
    lines.append("func (c *Client) Do(cmd any) (label, result string, err error) {")
    lines.append("\tswitch req := cmd.(type) {")

    # Build switch cases
    for tool in tools:
        go_name = go_method_name(tool.name)
        lines.append(f"\tcase {go_name}Request:")
        lines.append(f"\tlabel = \"{go_name}\"")
        lines.append(f"\tresult, err = c.{go_name}(req)")

    lines.append("""
\tdefault:
\t\treturn "", "", fmt.Errorf("unknown cmd type %T", cmd)
\t}
\treturn label, result, err
}
""")
    return "\n".join(lines)


def gen_tools_go(tools: list[ToolDef]) -> str:
    """Generate the tools.go file with one request struct + method per tool."""
    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    lines.append("")
    lines.append("package blender")
    lines.append("")

    # Group tools by category
    categories: dict[str, list[ToolDef]] = {}
    for t in tools:
        categories.setdefault(t.category, []).append(t)

    for category, cat_tools in categories.items():
        lines.append(f"// --- {category} ---")
        lines.append("")

        for tool in cat_tools:
            struct_name = go_struct_name(tool.name)
            go_name = go_method_name(tool.name)

            # Generate request struct
            lines.append(f"// {struct_name} holds parameters for the {tool.name} tool.")
            if tool.description:
                # First line of description
                first_line = tool.description.split("\n")[0]
                lines.append(f"// {first_line}")
            lines.append(f"type {struct_name} struct {{")

            for p in tool.params:
                field = go_field_name(p.name)
                py_type = p.py_type

                if p.has_default:
                    # Use pointer for optional params (except string, which uses "")
                    go_t = go_type(py_type)
                    if py_type in ("str", "str | None"):
                        # Use empty string as sentinel for "not set"
                        lines.append(f"\t{field} {go_t} `json:\"{p.name},omitempty\"`")
                    elif py_type == "bool":
                        lines.append(f"\t{field} *bool `json:\"{p.name},omitempty\"`")
                    elif py_type == "int" or py_type == "int | None":
                        lines.append(f"\t{field} *int `json:\"{p.name},omitempty\"`")
                    elif py_type.startswith("list["):
                        lines.append(f"\t{field} {go_t} `json:\"{p.name},omitempty\"`")
                    elif py_type.startswith("Literal["):
                        lines.append(f"\t{field} {go_t} `json:\"{p.name},omitempty\"`")
                    else:
                        lines.append(f"\t{field} {go_t} `json:\"{p.name},omitempty\"`")
                else:
                    go_t = go_type(py_type)
                    if py_type.startswith("Literal["):
                        lines.append(f"\t{field} {go_t} `json:\"{p.name}\"`")
                    else:
                        lines.append(f"\t{field} {go_t} `json:\"{p.name}\"`")

            lines.append("}")
            lines.append("")

            # Generate method on Client
            lines.append(f"// {go_name} calls the {tool.name} MCP tool.")
            if tool.description:
                for desc_line in tool.description.split("\n"):
                    desc_line = desc_line.strip()
                    if desc_line:
                        lines.append(f"// {desc_line}")
            lines.append(f"func (c *Client) {go_name}(req {struct_name}) (string, error) {{")

            # Build args map
            lines.append("\targs := map[string]any{}")
            for p in tool.params:
                field = go_field_name(p.name)
                py_type = p.py_type

                if p.has_default:
                    if py_type in ("str", "str | None"):
                        lines.append(f'\tif req.{field} != "" {{')
                        lines.append(f'\t\targs["{p.name}"] = req.{field}')
                        lines.append("\t}")
                    elif py_type == "bool":
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f'\t\targs["{p.name}"] = *req.{field}')
                        lines.append("\t}")
                    elif py_type == "int" or py_type == "int | None":
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f'\t\targs["{p.name}"] = *req.{field}')
                        lines.append("\t}")
                    elif py_type.startswith("list["):
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f'\t\targs["{p.name}"] = req.{field}')
                        lines.append("\t}")
                    elif py_type.startswith("Literal["):
                        lines.append(f'\tif req.{field} != "" {{')
                        lines.append(f'\t\targs["{p.name}"] = req.{field}')
                        lines.append("\t}")
                    else:
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f'\t\targs["{p.name}"] = req.{field}')
                        lines.append("\t}")
                else:
                    if py_type.startswith("list["):
                        lines.append(f'\targs["{p.name}"] = req.{field}')
                    elif py_type.startswith("dict["):
                        lines.append(f'\targs["{p.name}"] = req.{field}')
                    else:
                        lines.append(f'\targs["{p.name}"] = req.{field}')

            lines.append(f'\treturn c.callTool("{tool.name}", args)')
            lines.append("}")
            lines.append("")

    return "\n".join(lines)


def gen_go_mod(version: str = "1.0.0") -> str:
    """Generate go.mod."""
    return f"""module github.com/gmlewis/PicoGK/sdk/go/blender

go 1.22

// blender: Blender MCP SDK for Go
// Version: {version}
"""


