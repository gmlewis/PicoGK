def go_type(py_type: str) -> str:
    """Map a Python type to its Go equivalent."""
    base = py_type.strip().rstrip("]").lstrip("[")
    if py_type.startswith("list["):
        inner = py_type[5:-1]
        return f"[]{go_type(inner)}"
    if py_type.startswith("dict["):
        return "map[string]any"
    if py_type in ("str", "str | None"):
        return "string"
    if py_type in ("int", "int | None"):
        return "int"
    if py_type in ("bool",):
        return "bool"
    if py_type in ("float",):
        return "float64"
    if py_type in ("object", "any"):
        return "any"
    # Literal types (enum) -> string
    if py_type.startswith("Literal["):
        return "string"
    # Named type aliases (e.g., AreaUIType) -> string
    if py_type in ("AreaUIType",):
        return "string"
    return "any"


def go_zero(py_type: str) -> str:
    """Return the Go zero value for a type."""
    if py_type.startswith("list["):
        return "nil"
    if py_type.startswith("dict["):
        return "nil"
    if py_type in ("str", "str | None"):
        return '""'
    if py_type in ("int", "int | None"):
        return "0"
    if py_type in ("bool",):
        return "false"
    if py_type in ("float",):
        return "0"
    if py_type.startswith("Literal["):
        return '""'
    return "nil"


