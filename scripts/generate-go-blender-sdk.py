GENERATED_HEADER = "// Code generated by scripts/generate-go-blender-sdk.py — DO NOT EDIT.\n"

BLENDER_MCP_DIR = Path.home() / "Projects" / "Blender" / "blender_mcp" / "mcp" / "blmcp" / "tools"


