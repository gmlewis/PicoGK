def _find_tool_files() -> list[Path]:
    """Find all non-template, non-toolcode Python files in the tools directory."""
    files = []
    for f in sorted(BLENDER_MCP_DIR.glob("*.py")):
        if f.name.startswith("_"):
            continue
        if f.name.endswith("_toolcode.py"):
            continue
        files.append(f)
    return files


def _extract_docstring(source: str) -> str:
    """Extract the docstring from a function's source code."""
    try:
        tree = ast.parse(source)
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.body and isinstance(node.body[0], ast.Expr):
                    val = node.body[0].value
                    if isinstance(val, (ast.Constant, ast.Str)):
                        s = val.value if isinstance(val, ast.Constant) else val.s
                        return s.strip()
    except SyntaxError:
        pass
    return ""


def _parse_function_def(source: str) -> tuple[str, str, list[Param]]:
    """Parse a Python function definition, returning (name, docstring, params)."""
    tree = ast.parse(source)
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        if node.name.startswith("_"):
            continue
        if not any(isinstance(d, ast.Name) and d.id == "mcp"
                    for decorator in node.decorator_list
                    for d in ([decorator] if isinstance(decorator, ast.Name)
                              else ([decorator.func] if isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Name) else []))):
            # Check for @mcp.tool(...) pattern
            pass  # We'll include all functions that have decorators with 'tool'

        # Extract docstring
        docstring = ""
        if node.body and isinstance(node.body[0], ast.Expr):
            val = node.body[0].value
            if isinstance(val, (ast.Constant, ast.Str)):
                docstring = val.value if isinstance(val, ast.Constant) else val.s

        # Extract parameters
        params = []
        args = node.args
        # Build defaults mapping (defaults align from the end)
        num_defaults = len(args.defaults)
        num_args = len(args.args)
        for i, arg in enumerate(args.args):
            if arg.arg == "self":
                continue
            py_type = ""
            if arg.annotation:
                if isinstance(arg.annotation, ast.Name):
                    py_type = arg.annotation.id
                elif isinstance(arg.annotation, ast.Subscript):
                    if isinstance(arg.annotation.value, ast.Name):
                        base = arg.annotation.value.id
                        if isinstance(arg.annotation.slice, ast.Name):
                            inner = arg.annotation.slice.id
                        elif isinstance(arg.annotation.slice, ast.Tuple):
                            inner = ", ".join(
                                e.id if isinstance(e, ast.Name) else ast.dump(e)
                                for e in arg.annotation.slice.elts
                            )
                        else:
                            inner = ast.dump(arg.annotation.slice)
                        py_type = f"{base}[{inner}]"
                elif isinstance(arg.annotation, ast.BinOp):
                    # Union types: str | None
                    left = arg.annotation.left
                    right = arg.annotation.right
                    left_str = left.id if isinstance(left, ast.Name) else ast.dump(left)
                    right_str = right.id if isinstance(right, ast.Name) else ast.dump(right)
                    py_type = f"{left_str} | {right_str}"

            default_idx = i - (num_args - num_defaults)
            if default_idx >= 0:
                default_node = args.defaults[default_idx]
                if isinstance(default_node, ast.Constant):
                    default_val = repr(default_node.value)
                elif isinstance(default_node, ast.NameConstant):
                    default_val = str(default_node.value)
                elif isinstance(default_node, ast.Attribute):
                    default_val = ast.dump(default_node)
                else:
                    default_val = ast.dump(default_node)
                params.append(Param(
                    name=arg.arg,
                    py_type=py_type,
                    description="",
                    default=default_val,
                    has_default=True,
                ))
            else:
                params.append(Param(
                    name=arg.arg,
                    py_type=py_type,
                    description="",
                    default=None,
                    has_default=False,
                ))

        return node.name, docstring, params

    return "", "", []


def parse_all_tools() -> list[ToolDef]:
    """Parse all Blender MCP tools from the Python source files."""
    tools = []

    for filepath in _find_tool_files():
        source = filepath.read_text()

        # We need to find the functions registered as MCP tools
        # Each file typically has one or two @mcp.tool() decorated functions
        # Parse the AST to find them
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue

        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef):
                continue
            if node.name.startswith("_"):
                continue
            # Check for @mcp.tool decorator
            has_tool_decorator = False
            for decorator in node.decorator_list:
                if isinstance(decorator, ast.Call):
                    func = decorator.func
                    if isinstance(func, ast.Attribute) and func.attr == "tool":
                        has_tool_decorator = True
                        break
            if not has_tool_decorator:
                continue

            # Extract docstring
            docstring = ""
            if node.body and isinstance(node.body[0], ast.Expr):
                val = node.body[0].value
                if isinstance(val, (ast.Constant, ast.Str)):
                    docstring = val.value if isinstance(val, ast.Constant) else val.s
                    # Clean up: strip leading/trailing whitespace, normalize newlines
                    docstring = " ".join(docstring.split())

            # Extract parameters
            params = []
            args = node.args
            num_defaults = len(args.defaults)
            num_args = len(args.args)
            for i, arg in enumerate(args.args):
                if arg.arg == "self":
                    continue
                py_type = ""
                if arg.annotation:
                    py_type = _ast_type_to_str(arg.annotation)

                default_idx = i - (num_args - num_defaults)
                if default_idx >= 0:
                    default_node = args.defaults[default_idx]
                    default_val = _ast_value_to_str(default_node)
                    params.append(Param(
                        name=arg.arg,
                        py_type=py_type,
                        description="",
                        default=default_val,
                        has_default=True,
                    ))
                else:
                    params.append(Param(
                        name=arg.arg,
                        py_type=py_type,
                        description="",
                        default=None,
                        has_default=False,
                    ))

            # Determine category from filename
            category = _category_from_filename(filepath.stem)

            tools.append(ToolDef(
                name=node.name,
                description=docstring,
                category=category,
                params=params,
            ))

    return tools


def _ast_type_to_str(node: ast.AST) -> str:
    """Convert an AST type annotation node to a string."""
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Constant):
        return str(node.value)
    if isinstance(node, ast.Subscript):
        base = _ast_type_to_str(node.value)
        inner = _ast_type_to_str(node.slice)
        return f"{base}[{inner}]"
    if isinstance(node, ast.Tuple):
        parts = [_ast_type_to_str(e) for e in node.elts]
        return ", ".join(parts)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        left = _ast_type_to_str(node.left)
        right = _ast_type_to_str(node.right)
        return f"{left} | {right}"
    if isinstance(node, ast.Attribute):
        return f"{_ast_type_to_str(node.value)}.{node.attr}"
    return ast.dump(node)


def _ast_value_to_str(node: ast.AST) -> str:
    """Convert an AST default value node to a string."""
    if isinstance(node, ast.Constant):
        return repr(node.value)
    if isinstance(node, ast.NameConstant):
        return str(node.value)
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return f"{_ast_value_to_str(node.value)}.{node.attr}"
    return ast.dump(node)


def _category_from_filename(stem: str) -> str:
    """Determine category from the tool filename."""
    if stem.startswith("get_blendfile_summary"):
        return "Blend File"
    if stem.startswith("get_screenshot"):
        return "Screenshot"
    if stem.startswith("execute_blender_code"):
        return "Execute"
    if stem.startswith("get_python_api_docs") or stem.startswith("search_api_docs"):
        return "API Docs"
    if stem.startswith("search_manual_docs"):
        return "Manual Docs"
    if stem.startswith("get_objects_summary") or stem.startswith("get_object_detail"):
        return "Objects"
    if stem.startswith("render_"):
        return "Render"
    if stem.startswith("jump_to_tab"):
        return "Workspace"
    if stem.startswith("jump_to_view3d"):
        return "Viewport"
    return "Other"


