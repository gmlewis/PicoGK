def gen_tools_mbt(tools: list[ToolDef]) -> str:
    """Generate the tools.mbt file with one method per tool."""
    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    lines.append("")

    # Group tools by category
    categories: dict[str, list[ToolDef]] = {}
    for t in tools:
        categories.setdefault(t.category, []).append(t)

    for category, cat_tools in categories.items():
        lines.append(f"// === {category} ===")
        lines.append("")

        for tool in cat_tools:
            method_name = mbt_method_name(tool.name)

            # Build function signature
            params_sig: list[str] = []
            for p in tool.params:
                if p.has_default:
                    mbt_t = mbt_type_optional(p.py_type)
                else:
                    mbt_t = mbt_type(p.py_type)
                params_sig.append(f"{mbt_field_name(p.name)} : {mbt_t}")

            params_str = ", ".join(params_sig)

            # Build the args map construction
            args_lines: list[str] = []
            for p in tool.params:
                field = mbt_field_name(p.name)
                json_key = p.name
                if p.has_default:
                    if p.py_type == "int" or p.py_type == "int | None":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", Json::number(v.to_double()))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.py_type == "bool":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", Json::boolean(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.py_type.startswith("list["):
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(arr) => args.set(\"{json_key}\", Json::array(arr.map(fn(s) {{ Json::string(s) }})))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    else:
                        # String and other optional types
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", Json::string(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                else:
                    if p.py_type == "int":
                        args_lines.append(f"  args.set(\"{json_key}\", Json::number({field}.to_double()))")
                    elif p.py_type == "bool":
                        args_lines.append(f"  args.set(\"{json_key}\", Json::boolean({field}))")
                    elif p.py_type.startswith("list["):
                        args_lines.append(f"  args.set(\"{json_key}\", Json::array({field}.map(fn(s) {{ Json::string(s) }})))")
                    elif p.py_type.startswith("dict["):
                        args_lines.append(f"  args.set(\"{json_key}\", {field})")
                    else:
                        # String and other types
                        args_lines.append(f"  args.set(\"{json_key}\", Json::string({field}))")

            # Write doc comment
            desc = tool.description.replace('\n', '\n  ///')
            lines.append(f"///")
            lines.append(f"/// {method_name} — {tool.name}")
            lines.append(f"/// {desc}")
            lines.append(f"///")

            # Function signature
            if params_str:
                lines.append(f"pub async fn Client::{method_name}(self : Client, {params_str}) -> String raise {{")
            else:
                lines.append(f"pub async fn Client::{method_name}(self : Client) -> String raise {{")

            lines.append(f"  let args : Map[String, Json] = {{}}")
            if args_lines:
                lines.extend(args_lines)
            lines.append(f"  self.call_tool(\"{tool.name}\", args)")
            lines.append("}")
            lines.append("")

    return "\n".join(lines)


