def mbt_field_name(param_name: str) -> str:
    """Convert snake_case param name to MoonBit camelCase field name."""
    parts = param_name.split("_")
    result = parts[0]
    for p in parts[1:]:
        result += p[:1].upper() + p[1:]
    return result


def mbt_method_name(tool_name: str) -> str:
    """Convert snake_case tool name to MoonBit snake_case method name."""
    # Already snake_case, just use as-is
    return tool_name


