@dataclass
class Param:
    name: str
    py_type: str
    description: str
    default: str | None
    has_default: bool


@dataclass
class ToolDef:
    name: str
    description: str
    category: str
    params: list[Param] = field(default_factory=list)

    @property
    def required_params(self) -> list[Param]:
        return [p for p in self.params if not p.has_default]

    @property
    def optional_params(self) -> list[Param]:
        return [p for p in self.params if p.has_default]


# ---------------------------------------------------------------------------
# Python type -> MoonBit type mapping
# ---------------------------------------------------------------------------

def mbt_type(py_type: str) -> str:
    """Map a Python type to its MoonBit equivalent."""
    if py_type.startswith("list["):
        inner = py_type[5:-1]
        return f"Array[{mbt_type(inner)}]"
    if py_type.startswith("dict["):
        return "Map[String, Json]"
    if py_type in ("str", "str | None"):
        return "String"
    if py_type in ("int", "int | None"):
        return "Int"
    if py_type in ("bool",):
        return "Bool"
    if py_type in ("float",):
        return "Double"
    if py_type in ("object", "any"):
        return "Json"
    # Literal types (enum) -> String
    if py_type.startswith("Literal["):
        return "String"
    # Named type aliases (e.g., AreaUIType) -> String
    if py_type in ("AreaUIType",):
        return "String"
    return "Json"


def mbt_type_optional(py_type: str) -> str:
    """For optional params, MoonBit uses Option[T]."""
    return mbt_type(py_type) + "?"


def mbt_zero(py_type: str) -> str:
    """Return the MoonBit zero/default value."""
    if py_type.startswith("list["):
        return "[]"
    if py_type.startswith("dict["):
        return "{}"
    if py_type in ("str", "str | None"):
        return '""'
    if py_type in ("int", "int | None"):
        return "0"
    if py_type in ("bool",):
        return "false"
    if py_type in ("float",):
        return "0.0"
    if py_type.startswith("Literal["):
        return '""'
    return "None"


