def gen_readme_md(tools: list[ToolDef]) -> str:
    """Generate the SDK README.md."""
    tool_count = len(tools)
    category_list: dict[str, list[str]] = {}
    for t in tools:
        category_list.setdefault(t.category, []).append(t.snake_name)

    cat_table = "\n".join(
        f"| **{cat}** | {', '.join(names)} |"
        for cat, names in sorted(category_list.items())
    )

    return f"""# mbtpicogk — MoonBit SDK for the PicoGK MCP Server

`mbtpicogk` is an auto-generated MoonBit SDK for the [PicoGK](https://picogk.org)
geometry kernel's MCP (Model Context Protocol) server. It provides a fully typed,
idiomatic MoonBit interface to all {tool_count} PicoGK tools — from creating
primitives to boolean operations, lattice design, mesh manipulation, rendering, and
3D-printing export.

## Quick Start

```bash
moon add leap71/mbtpicogk
```

```moonbit
///|
fn main {{
  // Launch the PicoGK MCP server
  let client = @mbtpicogk.new_client("/path/to/PicoGK.Mcp")!

  // Initialize the geometry kernel (0.5mm voxels)
  let _ = client.picogk_init!(0.5)

  // Create a sphere
  let res = client.create_sphere!(0.0, 0.0, 0.0, 30.0, Some("body"))
  println(res)

  // Create a box cutout
  let _ = client.create_box!(-10.0, -10.0, -40.0, 10.0, 10.0, 40.0, Some("cutout"))

  // Subtract box from sphere
  let _ = client.boolean_subtract!("body", "cutout", Some("result"))

  // Smooth the result
  let _ = client.smooth!("result", 2.0, Some("smoothed"))

  // Convert to mesh and export STL
  let _ = client.voxels_to_mesh!("smoothed", Some("mesh"))
  let _ = client.save_stl!("mesh", "/tmp/part.stl")

  // Render a preview
  let _ = client.render_to_image!("smoothed", "/tmp/preview.png")

  // Clean up
  client.close()

  println("Done! Part exported to /tmp/part.stl")
}}
```

## API Overview

The SDK exposes all {tool_count} PicoGK MCP tools via typed methods:

| Category | Tools |
|----------|-------|
{cat_table}

Each tool has:
- A `Client::ToolName(...)` method with typed parameters
- Optional parameters are `Option[T]` (use `Some(value)` or `None`)
- Returns `String` (the tool's text response) or raises `String` on error
- Full doc comments

## Architecture

The SDK launches the PicoGK MCP server as a subprocess and communicates via
JSON-RPC over stdio. No network connection is needed. The server binary must
be installed separately (see the main PicoGK README for build instructions).

## Auto-Generation

This SDK is auto-generated from the PicoGK C# MCP tool definitions by
`scripts/generate-mbt-mcp-sdk.py`. To regenerate:

```bash
./scripts/generate-mbt-mcp-sdk.py --verbose
```

**DO NOT EDIT** the generated files — changes will be overwritten. Edit the
C# tool definitions in `PicoGK.Mcp/Tools/*.cs` instead, then regenerate.
"""


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Generate the MoonBit (mbtpicogk) MCP SDK from PicoGK C# tool definitions."
    )
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().parent.parent / "sdk" / "mbt",
        help="Output directory (default: sdk/mbt/)",
    )
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    tools = parse_mcp_tools()
    print(f"Parsed {len(tools)} tools from PicoGK.Mcp/Tools/*.cs")

    # Create output directories
    pkg_dir = args.output / "mbtpicogk"
    pkg_dir.mkdir(parents=True, exist_ok=True)

    # Generate files
    client_mbt = gen_client_mbt(tools)
    tools_mbt = gen_tools_mbt(tools)
    moon_mod = gen_moon_mod_json()
    moon_pkg = gen_moon_pkg_json()
    readme_md = gen_readme_md(tools)

    (pkg_dir / "client.mbt").write_text(client_mbt)
    (pkg_dir / "tools.mbt").write_text(tools_mbt)
    (pkg_dir / "moon.mod.json").write_text(moon_mod)
    (pkg_dir / "moon.pkg.json").write_text(moon_pkg)
    (pkg_dir / "README.md").write_text(readme_md)

    print(f"Generated MoonBit SDK in {pkg_dir}:")
    print(f"  client.mbt      ({len(client_mbt.splitlines()):>5} lines)")
    print(f"  tools.mbt       ({len(tools_mbt.splitlines()):>5} lines)")
    print(f"  moon.mod.json")
    print(f"  moon.pkg.json")
    print(f"  README.md       ({len(readme_md.splitlines()):>5} lines)")
    print(f"\n  Total: {len(tools)} tools across {len(set(t.category for t in tools))} categories")


if __name__ == "__main__":
    main()