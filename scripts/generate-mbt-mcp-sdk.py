def gen_tools_mbt(tools: list[ToolDef]) -> str:
    """Generate the tools.mbt file with one method per tool."""
    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    lines.append("")
    # Group tools by category
    categories: dict[str, list[ToolDef]] = {}
    for t in tools:
        categories.setdefault(t.category, []).append(t)

    for category, cat_tools in categories.items():
        lines.append(f"// === {category} ===")
        lines.append("")

        for tool in cat_tools:
            method_name = mbt_method_name(tool.name)
            # Build function signature
            params_sig: list[str] = []
            for p in tool.params:
                if p.has_default:
                    mbt_t = mbt_type_for_optional(p.cs_type)
                else:
                    mbt_t = mbt_type(p.cs_type)
                params_sig.append(f"{mbt_field_name(p.name)} : {mbt_t}")

            params_str = ", ".join(params_sig)

            # Build the args map construction
            args_lines: list[str] = []
            for p in tool.params:
                field = mbt_field_name(p.name)
                json_key = p.name
                if p.has_default:
                    if p.cs_type == "string[]":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(arr) => args.set(\"{json_key}\", JsonValue::Array(arr.map(fn(s) {{ JsonValue::String(s) }})))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.cs_type == "float":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", JsonValue::Number(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.cs_type == "int":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", JsonValue::Int(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.cs_type == "bool":
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", JsonValue::Bool(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                    elif p.cs_type in ("string", "string?"):
                        args_lines.append(f"  match {field} {{")
                        args_lines.append(f"    Some(v) => args.set(\"{json_key}\", JsonValue::String(v))")
                        args_lines.append(f"    None => ()")
                        args_lines.append(f"  }}")
                else:
                    if p.cs_type == "float":
                        args_lines.append(f"  args.set(\"{json_key}\", JsonValue::Number({field}))")
                    elif p.cs_type == "int":
                        args_lines.append(f"  args.set(\"{json_key}\", JsonValue::Int({field}))")
                    elif p.cs_type == "bool":
                        args_lines.append(f"  args.set(\"{json_key}\", JsonValue::Bool({field}))")
                    elif p.cs_type in ("string", "string?"):
                        args_lines.append(f"  args.set(\"{json_key}\", JsonValue::String({field}))")
                    elif p.cs_type == "string[]":
                        args_lines.append(f"  args.set(\"{json_key}\", JsonValue::Array({field}.map(fn(s) {{ JsonValue::String(s) }})))")

            # Write doc comment
            # Escape the description for MoonBit comments
            desc = tool.description.replace('\n', '\n  ///')
            lines.append(f"///")
            lines.append(f"/// {method_name} — {tool.snake_name}")
            lines.append(f"/// {desc}")
            lines.append(f"///")

            # Function signature
            if params_str:
                lines.append(f"pub fn Client::{tool.name}(self : Client, {params_str}) -> String!String {{")
            else:
                lines.append(f"pub fn Client::{tool.name}(self : Client) -> String!String {{")

            lines.append(f"  let args : Map[String, JsonValue] = {{}}")
            if args_lines:
                lines.extend(args_lines)
            lines.append(f"  self.call_tool!(\"{tool.snake_name}\", args)")
            lines.append("}")
            lines.append("")

    return "\n".join(lines)


