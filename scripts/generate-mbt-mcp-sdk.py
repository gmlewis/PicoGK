GENERATED_HEADER = "// Code generated by scripts/generate-mbt-mcp-sdk.py — DO NOT EDIT.\n"


# ---------------------------------------------------------------------------
# Type mapping: C# -> MoonBit
# ---------------------------------------------------------------------------

def mbt_type(cs_type: str) -> str:
    """Map a C# type to its MoonBit equivalent."""
    if cs_type == "float":
        return "Double"
    if cs_type == "int":
        return "Int"
    if cs_type == "bool":
        return "Bool"
    if cs_type in ("string", "string?"):
        return "String"
    if cs_type == "string[]":
        return "Array[String]"
    return "Unit"


def mbt_type_for_optional(cs_type: str) -> str:
    """For optional params, MoonBit uses Option[T]."""
    if cs_type == "float":
        return "Double?"
    if cs_type == "int":
        return "Int?"
    if cs_type == "bool":
        return "Bool?"
    if cs_type in ("string", "string?"):
        return "String?"
    if cs_type == "string[]":
        return "Array[String]?"  # nil means not set
    return "Unit"


def mbt_zero(cs_type: str) -> str:
    """Return the MoonBit zero/default value."""
    if cs_type == "float":
        return "0.0"
    if cs_type == "int":
        return "0"
    if cs_type == "bool":
        return "false"
    if cs_type in ("string", "string?"):
        return '""'
    if cs_type == "string[]":
        return "[]"
    return "Unit"


# ---------------------------------------------------------------------------
# Name conversion
# ---------------------------------------------------------------------------

def mbt_field_name(param_name: str) -> str:
    """Convert snake_case param name to MoonBit camelCase field name."""
    parts = param_name.split("_")
    result = parts[0]
    for p in parts[1:]:
        result += p[:1].upper() + p[1:]
    return result


def mbt_method_name(tool_name: str) -> str:
    """Convert PascalCase to MoonBit snake_case method name."""
    import re
    result = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", tool_name)
    result = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", result)
    return result.lower()


