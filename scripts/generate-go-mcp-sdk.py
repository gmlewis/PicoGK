def gen_tools_go(tools: list[ToolDef]) -> str:
    """Generate the tools.go file with one builder struct + method per tool."""
    lines: list[str] = []
    lines.append(GENERATED_HEADER)
    lines.append("")
    lines.append("package picogk")
    lines.append("")
    lines.append("import (")
    lines.append('\t"context"')
    lines.append(")")
    lines.append("")

    # Group tools by category
    categories: dict[str, list[ToolDef]] = {}
    for t in tools:
        categories.setdefault(t.category, []).append(t)

    for category, cat_tools in categories.items():
        lines.append(f"// --- {category} ---")
        lines.append("")

        for tool in cat_tools:
            # Generate request struct
            req_struct = f"{tool.name}Request"
            lines.append(f"// {req_struct} holds parameters for the {tool.snake_name} tool.")
            lines.append(f"// {tool.description}")
            lines.append(f"type {req_struct} struct {{")
            for p in tool.params:
                go_t = go_type(p.cs_type)
                field = go_field_name(p.name)
                json_tag = p.name
                if p.has_default:
                    # Use pointer for optional params so we can distinguish "not set"
                    if p.cs_type == "float":
                        go_t = "*float64"
                    elif p.cs_type == "int":
                        go_t = "*int"
                    elif p.cs_type == "bool":
                        go_t = "*bool"
                    elif p.cs_type in ("string", "string?"):
                        go_t = "*string"
                    elif p.cs_type == "string[]":
                        go_t = "[]string"  # nil means not set
                    # json omitempty for optionals
                    lines.append(f"\t{field} {go_t} `json:\"{json_tag},omitempty\"`")
                else:
                    lines.append(f"\t{field} {go_t} `json:\"{json_tag}\"`")
            lines.append("}")
            lines.append("")

            # Generate method on Client
            lines.append(f"// {tool.name} calls the {tool.snake_name} MCP tool.")
            lines.append(f"// {tool.description}")
            if tool.required_params:
                req_params_str = ", ".join(
                    p.name for p in tool.required_params
                )
            lines.append(f"func (c *Client) {tool.name}(ctx context.Context, req {req_struct}) (string, error) {{")

            # Build args map
            lines.append("\targs := map[string]interface{}{}")
            for p in tool.params:
                field = go_field_name(p.name)
                if p.has_default:
                    if p.cs_type == "string[]":
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f"\t\targs[\"{p.name}\"] = req.{field}")
                        lines.append(f"\t}}")
                    else:
                        lines.append(f"\tif req.{field} != nil {{")
                        lines.append(f"\t\targs[\"{p.name}\"] = *req.{field}")
                        lines.append(f"\t}}")
                else:
                    if p.cs_type == "string[]":
                        lines.append(f"\targs[\"{p.name}\"] = req.{field}")
                    else:
                        lines.append(f"\targs[\"{p.name}\"] = req.{field}")

            lines.append(f"\treturn c.callTool(ctx, \"{tool.snake_name}\", args)")
            lines.append("}")
            lines.append("")

    return "\n".join(lines)


