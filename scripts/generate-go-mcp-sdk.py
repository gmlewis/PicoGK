# ---------------------------------------------------------------------------
# Type mapping: C# -> Go
# ---------------------------------------------------------------------------

def go_type(cs_type: str) -> str:
    """Map a C# type to its Go equivalent."""
    if cs_type == "float":
        return "float64"
    if cs_type == "int":
        return "int"
    if cs_type == "bool":
        return "bool"
    if cs_type in ("string", "string?"):
        return "string"
    if cs_type == "string[]":
        return "[]string"
    return "interface{}"


def go_zero(cs_type: str) -> str:
    """Return the Go zero value for a type."""
    if cs_type == "float":
        return "0"
    if cs_type == "int":
        return "0"
    if cs_type == "bool":
        return "false"
    if cs_type in ("string", "string?"):
        return '""'
    if cs_type == "string[]":
        return "nil"
    return "nil"


def go_json_type(cs_type: str) -> str:
    """Return how the value should appear in JSON encoding."""
    if cs_type == "float":
        return "float64"
    if cs_type == "int":
        return "int"
    if cs_type == "bool":
        return "bool"
    if cs_type in ("string", "string?"):
        return "string"
    if cs_type == "string[]":
        return "[]string"
    return "interface{}"


def is_pointer_optional(cs_type: str) -> bool:
    """For string? we still use string (Go strings are nil-able via "")."""
    return False


# ---------------------------------------------------------------------------
# Name conversion
# ---------------------------------------------------------------------------

def go_field_name(param_name: str) -> str:
    """Convert snake_case param name to Go-idiomatic exported field name."""
    parts = param_name.split("_")
    return "".join(p[:1].upper() + p[1:] for p in parts)


